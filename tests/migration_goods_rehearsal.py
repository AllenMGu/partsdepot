"""Execute the one-time goods migration on isolated legacy-shaped PostgreSQL data."""

import os
from pathlib import Path
from uuid import uuid4

import psycopg2


def main():
    url = os.environ["WMS_DATABASE_URL"].replace("postgresql+psycopg2://", "postgresql://", 1)
    schema = "migration_test_" + uuid4().hex[:12]
    conn = psycopg2.connect(url)
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(f"CREATE SCHEMA {schema}")
            cur.execute(f"SET search_path TO {schema}, public")
            cur.execute("""
                CREATE TABLE warehouses (id integer PRIMARY KEY, is_active boolean NOT NULL);
                INSERT INTO warehouses VALUES (1, true), (2, true);
                CREATE TABLE goods (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    barcode varchar(100) UNIQUE, name varchar(100), spec varchar(100),
                    unit varchar(20), price double precision, create_time timestamp
                );
                CREATE INDEX ix_goods_barcode ON goods(barcode);
                INSERT INTO goods(id, barcode, name, spec, unit, price, create_time)
                VALUES (10, 'SHARED', '旧全局货物', '', '个', 3, now());
                SELECT setval(pg_get_serial_sequence('goods', 'id'), 10);
                CREATE TABLE stock (id integer, warehouse_id integer, goods_id integer, location_id integer);
                INSERT INTO stock VALUES (1, 1, 10, 1);
                CREATE TABLE inventory_records (id integer, warehouse_id integer, goods_id integer);
                CREATE TABLE check_records (id integer, warehouse_id integer, goods_id integer);
                CREATE TABLE check_order_header (id integer, warehouse_id integer);
                CREATE TABLE check_order_item (id integer, header_id integer, goods_id integer);
                CREATE TABLE inbound_order_header (id integer, warehouse_id integer);
                CREATE TABLE inbound_order_item (id integer, header_id integer, goods_id integer);
                CREATE TABLE outbound_order_header (id integer, warehouse_id integer);
                CREATE TABLE outbound_order_item (id integer, header_id integer, goods_id integer);
                CREATE TABLE requests (id integer, warehouse_id integer, status varchar(20));
                CREATE TABLE request_items (id integer, request_id integer, barcode varchar(100));
                INSERT INTO requests VALUES (1, 2, 'pending');
                INSERT INTO request_items VALUES (1, 1, 'SHARED');
            """)
            sql = (Path(__file__).resolve().parents[1] / "migrations/20261022_goods_by_warehouse.sql").read_text()
            cur.execute(sql)
            cur.execute("SELECT id, warehouse_id FROM goods WHERE barcode='SHARED' ORDER BY warehouse_id")
            goods = cur.fetchall()
            assert len(goods) == 2 and [row[1] for row in goods] == [1, 2], goods
            assert goods[0][0] == 10 and goods[1][0] != 10, goods
            cur.execute("SELECT goods_id FROM stock WHERE warehouse_id=1")
            assert cur.fetchone()[0] == 10
            print("PASS | PostgreSQL 旧库迁移：无库存的 B 仓待处理申请仍获得独立货物档案")
    finally:
        with conn.cursor() as cur:
            cur.execute("SET search_path TO public")
            cur.execute(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
        conn.close()


if __name__ == "__main__":
    main()
